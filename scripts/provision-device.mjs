// Connects the REAL ESP32 controller to the owner's feeder in the LOCAL
// emulator. The backend's device-registration step, done by hand for now.
//
//   npm run device:provision -- --out "C:\path\to\AgriFeed_code\agrifeed_device.h"
//   npm run device:provision -- fd_XXXX --out ...      (a specific feeder)
//
// It switches the feeder from 'simulated' to 'live' (deviceRegistry and
// meta.mode, both backend-only paths), activates the device identity
// `esp32-<feederId>`, and writes the feeder ID and the device's custom token
// into the sketch's agrifeed_device.h. The ESP32 signs in with that token
// and then writes through the Security Rules with source 'device'.
//
// After this the Node simulator no longer drives the feeder (it only runs on
// simulated feeders). `npm run seed` resets everything back to simulated.
import { writeFileSync } from 'node:fs';
import { assertEmulatorRunning, auth, db } from './emulator-admin.mjs';

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
const out = outAt >= 0 ? args[outAt + 1] : null;
let feederId = args.find((a, i) => !a.startsWith('--') && i !== outAt + 1);

await assertEmulatorRunning();

if (!feederId) {
  const owner = await auth.getUserByEmail('owner@agrifeed.test').catch(() => null);
  const index = owner ? (await db.ref(`userFeeders/${owner.uid}`).get()).val() : null;
  feederId = index ? Object.keys(index)[0] : null;
}
if (!feederId) {
  console.error('No feeder found. Run "npm run seed" first, or pass a feeder ID.');
  process.exit(1);
}

const reg = (await db.ref(`deviceRegistry/${feederId}`).get()).val();
if (!reg) {
  console.error(`Feeder ${feederId} has no deviceRegistry entry.`);
  process.exit(1);
}

const deviceUid = `esp32-${feederId}`;
const credVersion = reg.credentialVersion ?? 1;
await db.ref().update({
  [`deviceRegistry/${feederId}/mode`]: 'live',
  [`deviceRegistry/${feederId}/status`]: 'active',
  [`deviceRegistry/${feederId}/deviceUid`]: deviceUid,
  [`deviceRegistry/${feederId}/credentialVersion`]: credVersion,
  [`feeders/${feederId}/meta/mode`]: 'live',
  // Simulator controls are meaningless for a real machine.
  [`feeders/${feederId}/simulator`]: null,
});

const claims = { device: true, feederId, mode: 'live', credVersion };
const token = await auth.createCustomToken(deviceUid, claims);

const header = `// Generated by "npm run device:provision" for the LOCAL emulator.
// Re-generate after "npm run seed" (the seed creates a new feeder ID).
// Emulator-only credential: production devices get theirs from the backend.
#pragma once
#define AGRIFEED_FEEDER_ID    "${feederId}"
#define AGRIFEED_DEVICE_TOKEN "${token}"
`;

if (out) {
  writeFileSync(out, header);
  console.log(`Wrote ${out}`);
} else {
  console.log(header);
}
console.log(`Feeder ${feederId} is now LIVE; device identity ${deviceUid} is active.`);
console.log('Upload the sketch again so the ESP32 picks up the new agrifeed_device.h.');
process.exit(0);
